"""Generates crates/registry/src/inventory.rs from spec/A_command_registry.md (the command index, read-only).

Run from the repository root: python scripts/gen-command-inventory.py
The Rust test `crates/registry/tests/inventory.rs` parses the spec independently and fails if the generated table
drifts from it, so the generator only needs re-running after the spec changes.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "A_command_registry.md"
OUT = ROOT / "crates" / "registry" / "src" / "inventory.rs"

ROW = re.compile(r"^\| `(?P<id>[^`]+)` \| (?P<kind>\w+) \| (?P<rest>.*) \|$")
NAMESPACE = re.compile(r"^## Namespace `(?P<ns>[^`]+)`")
DEFINED = re.compile(r"^Defined in \[`(?P<file>[^`]+)`\]")


def split_cells(rest: str) -> list[str]:
    """Splits the remaining table cells on `|` that are not escaped as `\\|`."""
    cells, cur, i = [], [], 0
    while i < len(rest):
        if rest[i] == "\\" and i + 1 < len(rest) and rest[i + 1] == "|":
            cur.append("|")
            i += 2
            continue
        if rest[i] == "|":
            cells.append("".join(cur).strip())
            cur = []
            i += 1
            continue
        cur.append(rest[i])
        i += 1
    cells.append("".join(cur).strip())
    return cells


def rust_str(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def parse() -> list[dict]:
    entries, ns, section = [], None, None
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        m = NAMESPACE.match(line)
        if m:
            ns, section = m["ns"], None
            continue
        m = DEFINED.match(line)
        if m:
            section = m["file"].split("_")[0]
            continue
        m = ROW.match(line)
        if m and ns:
            summary, params, result, undo = split_cells(m["rest"])
            entries.append(
                {"id": m["id"], "kind": m["kind"], "ns": ns, "section": section, "summary": summary,
                 "params": params, "result": result, "undo": undo}
            )
    return entries


def main() -> int:
    entries = parse()
    kinds = {"action": "Action", "toggle": "Toggle", "query": "Query", "job": "Job", "ui": "Ui", "event": "Event"}
    lines = [
        "// @generated by scripts/gen-command-inventory.py from spec/A_command_registry.md. Do not edit.",
        "//! The full command inventory of spec A (796 entries): id, kind, namespace, owning section and the spec's",
        "//! summary, parameter, result and undo columns verbatim. `tests/inventory.rs` keeps it equal to the spec.",
        "",
        "use crate::{InventoryEntry, Kind};",
        "",
        "/// Every entry of spec A, in spec order.",
        "pub static INVENTORY: &[InventoryEntry] = &[",
    ]
    for e in entries:
        lines.append("    InventoryEntry {")
        lines.append(f"        id: {rust_str(e['id'])},")
        lines.append(f"        kind: Kind::{kinds[e['kind']]},")
        lines.append(f"        namespace: {rust_str(e['ns'])},")
        lines.append(f"        section: {rust_str(e['section'])},")
        lines.append(f"        summary: {rust_str(e['summary'])},")
        lines.append(f"        params: {rust_str(e['params'])},")
        lines.append(f"        result: {rust_str(e['result'])},")
        lines.append(f"        undo: {rust_str(e['undo'])},")
        lines.append("    },")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(entries)} entries -> {OUT.relative_to(ROOT)}")
    return 0 if len(entries) == 796 else 1


if __name__ == "__main__":
    sys.exit(main())
