"""Regenerates reviews/evidence/M0-C0.3/vello-dependency-audit.txt (C03-R1-06).

Usage: python scripts/audit-vello-deps.py [--out <file>]

Method, stated in the output:
* graph: every crate printed by `cargo tree --locked -p vello_cpu --prefix none` in this workspace (resolved features;
  normal and build dependencies, e.g. `autocfg`; vello_cpu's own dev-dependencies are not part of the lock graph);
* sources: every `*.rs` file under each crate's `src/` in the local cargo registry;
* "lines" = all lines of those files; "unsafe lines" = lines matching the whole word `unsafe` whose first
  non-blank characters are not `//` (a lexical exposure indicator, not a count of unsafe blocks or a safety proof);
* libm call sites: `.name(` calls of libm-backed float methods in vello_common, vello_cpu, kurbo, peniko and color,
  **excluding code inside `#[cfg(test)]` items** (tracked by brace depth), each listed with file:line.
Standard library only.
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "reviews/evidence/M0-C0.3/vello-dependency-audit.txt"
LIBM = ("sin", "cos", "tan", "asin", "acos", "atan", "atan2", "sin_cos", "powf", "powi", "exp", "exp2", "ln", "log2",
        "log10", "hypot", "cbrt", "sinh", "cosh", "tanh")
CALL_CRATES = ("vello_common", "vello_cpu", "kurbo", "peniko", "color")


def registry():
    home = pathlib.Path.home() / ".cargo" / "registry" / "src"
    dirs = sorted(home.glob("index.crates.io-*"))
    if not dirs:
        raise SystemExit("cargo registry sources not found; run `cargo fetch` first")
    return dirs[0]


def license_of(folder):
    text = (folder / "Cargo.toml").read_text(encoding="utf-8")
    m = re.search(r'^license\s*=\s*"([^"]*)"', text, re.M)
    return m.group(1) if m else "-"


def production_lines(path):
    """(line number, text) of lines outside `#[cfg(test)]` items."""
    out, skip_depth, pending, depth = [], None, False, 0
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if skip_depth is None and stripped.startswith("#[cfg(test)]"):
            pending = True
            continue
        opens, closes = line.count("{"), line.count("}")
        if pending and opens:
            skip_depth, pending = depth, False
        if skip_depth is None and not pending:
            out.append((n, line))
        depth += opens - closes
        if skip_depth is not None and depth <= skip_depth:
            skip_depth = None
    return out


def main(argv):
    out_path = pathlib.Path(argv[argv.index("--out") + 1]) if "--out" in argv else OUT
    tree = subprocess.check_output(["cargo", "tree", "--locked", "-p", "vello_cpu", "--prefix", "none"], cwd=ROOT,
                                   text=True)
    crates = sorted(set(re.findall(r"^([\w-]+) v([\d.]+)", tree, re.M)))
    reg = registry()
    rows, total_lines, total_unsafe = [], 0, 0
    for name, version in crates:
        folder = reg / f"{name}-{version}"
        lines = [ln for f in sorted((folder / "src").rglob("*.rs")) for ln in f.read_text(encoding="utf-8").splitlines()]
        unsafe = sum(1 for ln in lines if re.search(r"\bunsafe\b", ln) and not ln.lstrip().startswith("//"))
        total_lines += len(lines)
        total_unsafe += unsafe
        rows.append(f"{name} v{version} | {license_of(folder)} | {unsafe} | {len(lines)}")
    calls = []
    for name, version in crates:
        if name not in CALL_CRATES:
            continue
        folder = reg / f"{name}-{version}"
        for f in sorted((folder / "src").rglob("*.rs")):
            for n, line in production_lines(f):
                if line.lstrip().startswith("//"):
                    continue
                for fn in re.findall(r"\.(" + "|".join(LIBM) + r")\(", line):
                    calls.append(f"{name}-{version}/{f.relative_to(folder).as_posix()}:{n}: {fn}: {line.strip()[:110]}")
    text = [
        "# vello_cpu dependency audit (C0.3), generated by scripts/audit-vello-deps.py",
        "# Graph: `cargo tree --locked -p vello_cpu --prefix none` (resolved features std, u8_pipeline, f32_pipeline,",
        "# multithreading; normal and build dependencies). Sources: src/**/*.rs in the cargo registry.",
        "# Columns: crate version | licence | lines matching the whole word `unsafe`, excluding `//` lines | source lines",
        *rows,
        f"# TOTAL: {len(rows)} crates (vello_cpu included), {total_lines} source lines, {total_unsafe} unsafe-word lines",
        "# These are lexical exposure indicators, not counts of unsafe blocks and not a safety proof. vello_cpu and",
        "# vello_common contain no `unsafe` themselves.",
        "",
        "# libm-backed float calls in production code (code inside #[cfg(test)] items excluded):",
        *calls,
        "",
        "# Paths relevant to the C0.3 adapter (bevel joins, butt caps, solid/linear/radial paint, clips; no blur, no",
        "# blurred rounded rectangles, no round joins or caps): kurbo stroke expansion uses `hypot` for segment",
        "# normalisation (used by every stroked fixture); round joins/caps and offset curves use angle functions",
        "# (`atan2`, `sin_cos`; not exercised by bevel/butt strokes); vello_common filter/gaussian_blur.rs `powf` for",
        "# blur weights and vello_cpu fine/common/rounded_blurred_rect.rs `exp`/`powf` (not used by the fixtures).",
        "# vello_common's flattening subdivision estimate uses an integer-power lookup table in production; the",
        "# `powf(1/6)` variant at flatten_simd.rs:671 is test-only (`old_estimate` in `mod tests`). The scalar-versus-SIMD",
        "# pixel differences (C03-R1-04) are not attributed to any particular one of these operations.",
    ]
    out_path.write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} crates, {total_lines} lines, {total_unsafe} unsafe-word lines, {len(calls)} libm call sites -> "
          f"{out_path.relative_to(ROOT) if out_path.is_relative_to(ROOT) else out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
