def inventory() -> list[str]:
    """Every control id of the parity manifest's DOM rows (each sends a command)."""
    rows = json.loads(PARITY.read_text(encoding="utf-8"))["dom"]
    return sorted({r["id"] for r in rows if r.get("commands")})


def table_templates() -> list[re.Pattern]:
    """The row names the D-39 script defines, as patterns: an f-string's `{...}` matches the text of one name segment
    (no `›`). A name made of placeholders alone (`{path[0]} › {label}`) would match any name and is left out: its rows
    cannot be named here."""
    text = TABLE.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r"\"name\":\s*(f?)\"((?:[^\"\\]|\\.)*)\"", text):
        name = m.group(2).replace('\\"', '"')
        if m.group(1):
            parts = re.split(r"\{[^{}]*\}", name)
            if not "".join(parts).replace("›", "").strip():
                continue
            out.append(re.compile("^" + "[^›]+".join(re.escape(p) for p in parts) + "$"))
        else:
            out.append(re.compile("^" + re.escape(name) + "$"))
    return out


def _d44_rows() -> set[str]:
    spec = importlib.util.spec_from_file_location("c43_d44_coverage", ROOT / "scripts" / "c43_d44_coverage.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.covered_rows()


