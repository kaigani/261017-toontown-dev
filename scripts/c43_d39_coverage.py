"""The D-39 bindings table's coverage of every commanded control the window renders (ruling D-59 item 2, C44A-R1S-02).

`inventory()` is the generated control inventory: every control id of the parity manifest's DOM rows
(`desktop/src/ui-bindings/parity.json`, generated by `pnpm --dir desktop parity:gen` from the rendered surfaces; each
row names the command a click sends). `COVERAGE` maps control-id patterns (`fnmatch`, case-sensitive) to the rows of
`scripts/c43-d39-bindings.py` that exercise the control (`rows`), to the D-44 rows that exercise a dialog's button
(`d44`, names from `scripts/c43_d44_coverage.py`), or to the reason it has neither (`reason`). `problems()` names every
control no pattern covers, every pattern that matches no control, every row name the D-39 script does not define and
every D-44 row the D-44 coverage does not list: a new commanded control without a row or a reason fails
(`scripts/test_c43_d39_inventory.py`, run in CI). The D-39 script checks at the end of a full run that every row named
here ran (or was named, with its reason, in the MCP form). Pure: no application, no MCP.

D-39's scope is the bindings added from C4.3b on. A control the window has had since C4.1 is listed with the reason
`BEFORE_D39` (Vitest and the parity gate cover it; no real-window row), so the list of such controls is visible and
cannot grow silently: a control added after C4.3b needs a row.
"""

