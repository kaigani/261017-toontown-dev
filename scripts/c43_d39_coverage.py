def _matches(pattern: str, control: str) -> bool:
    return fnmatch.fnmatchcase(control, pattern)


def problems(items: list[str] | None = None) -> list[str]:
    items = inventory() if items is None else items
    out = [f"{i}: a commanded control without a D-39 row or a reason" for i in items
           if not any(_matches(p, i) for p in COVERAGE)]
    out += [f"{p}: listed in the D-39 coverage but matches no control of the generated inventory" for p in COVERAGE
            if not any(_matches(p, i) for i in items)]
    templates = table_templates()
    d44 = _d44_rows()
    for p, v in COVERAGE.items():
        if not v.get("rows") and not v.get("d44") and not v.get("reason"):
            out.append(f"{p}: neither rows nor a reason")
        for name in v.get("rows", []):
            # A template name ("tools palette › {tool}") stands for the rows its loop makes.
            if not any(t.match(name) for t in templates):
                out.append(f"{p}: the D-39 script defines no row named {name!r}")
        for name in v.get("d44", []):
            if name not in d44:
                out.append(f"{p}: the D-44 coverage lists no row named {name!r}")
    return out


def named_rows() -> set[str]:
    """The concrete D-39 row names this coverage names (template names, which stand for a loop's rows, excluded)."""
    return {r for v in COVERAGE.values() for r in v.get("rows", []) if "{" not in r}


def before_d39() -> list[str]:
    """The patterns listed only because they predate D-39 (the visible list that cannot grow silently)."""
    return sorted(p for p, v in COVERAGE.items() if v.get("reason", "").startswith(BEFORE_D39))


