"""Generate independent synthetic decoder fixtures. No third-party image assets."""
import hashlib
import io
import json
from pathlib import Path
import random
import struct
import zlib

ROOT=Path(__file__).resolve().parents[2]

def generate():
    from PIL import Image
    out=ROOT/'tests/fixtures/vectorize/review-r1'
    out.mkdir(parents=True,exist_ok=True)
    rng=random.Random(0xC24A1102)
    files={}
    def add(name,data): files[name]=data
    for mode,fmt,opts in [('RGB','JPEG',{'progressive':True}),('P','PNG',{}),('RGBA','PNG',{}),('I;16','PNG',{}),('RGB','TIFF',{'big_tiff':True})]:
        img=Image.new(mode,(17,19))
        b=io.BytesIO(); img.save(b,format=fmt,**opts)
        add(f'{mode.replace(";","-")}.{fmt.lower()}',b.getvalue())
    frames=[Image.new('RGBA',(8,9),(v,0,0,255)) for v in [32,96,240]]
    b=io.BytesIO(); frames[0].save(b,format='GIF',save_all=True,append_images=frames[1:]); add('three-frames.gif',b.getvalue())
    def chunk(k,d): return struct.pack('>I',len(d))+k+d+struct.pack('>I',zlib.crc32(k+d))
    def png(w,h,raw,interlace=0):
        return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,6,0,0,interlace))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
    for w,h in [(0,0),(1,1024),(1024,1),(0xffffffff,1),(16385,1)]:
        add(f'size-{w}-{h}.png',png(w,h,(b'\0'+b'\x10\x20\x30\xff'*w)*h if w<=1024 else b''))
    # Valid Adam7 1x1: only pass 1 contributes one RGBA sample.
    add('adam7.png',png(1,1,b'\0\x12\x34\x56\x78',1))
    # Small dimensions, 16 MiB compressed output: decoder must not trust decompressed length.
    add('overlong-idat.png',png(1,1,b'\0'*(16<<20)))
    # PSD with nonempty opaque layer/mask section and a 2x2 RGB composite.
    psd=b'8BPS'+struct.pack('>H6sHIIHH',1,b'\0'*6,3,2,2,8,3)
    psd+=struct.pack('>III',0,0,12)+bytes(12)+struct.pack('>H',0)+bytes([32]*4+[64]*4+[128]*4)
    add('layer-section.psd',psd)
    for name,data in list(files.items()):
        for i,n in enumerate([0,1,7,len(data)//2,len(data)-1]): add(f'trunc-{i}-{name}',data[:max(0,n)])
    originals=list(files.items())
    for i in range(128):
        name,data=rng.choice(originals); data=bytearray(data)
        for _ in range(1+rng.randrange(5)):
            if data: data[rng.randrange(len(data))]=rng.randrange(256)
        add(f'mut-{i:03}-{name}',bytes(data))
    for n,b in files.items(): (out/n).write_bytes(b)
    (out/'PROVENANCE.md').write_text('Synthetic reviewer corpus generated by tests/adversarial/c24-r1-corpus.py; Python random seed 0xC24A1102; Pillow 11.3.0. PNG headers/chunks and flattened layered PSD built with struct/zlib. Adam7 one-pixel pass, dimensions, overlong IDAT, palette/alpha/16-bit, progressive JPEG, BigTIFF, multi-frame GIF, truncations and 128 mutations. No external assets. Regeneration is explicit: --generate.\n')
    (out/'manifest.json').write_text(json.dumps({n:hashlib.sha256(b).hexdigest() for n,b in files.items()},indent=2))
    print(len(files),'fixtures generated')

if __name__=='__main__':
    import sys
    if '--generate' in sys.argv: generate()
    else:
        import unittest
        class Corpus(unittest.TestCase):
            def test_hashes(self):
                out=ROOT/'tests/fixtures/vectorize/review-r1'
                for n,h in json.loads((out/'manifest.json').read_text()).items(): self.assertEqual(hashlib.sha256((out/n).read_bytes()).hexdigest(),h,n)
        unittest.main()
